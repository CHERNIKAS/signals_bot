"""Утилиты: нормализация символов, таймфреймов, конверторы"""

import re
from typing import Optional

_SYMBOL_ALIASES = {
    "PEPEUSDT": "1000PEPEUSDT",
}


# ============================================================================
# ФУНКЦИЯ: normalize_symbol
# ОПИСАНИЕ: Нормализует название торговой пары к формату XXXUSDT
#           Принимает любой текст (sol, SOLUSDT, Sol usdt) и приводит к стандарту
# ============================================================================
def normalize_symbol(text: str) -> Optional[str]:
    """
    Принимает что угодно типа 'sol', 'SOLUSDT', 'Sol usdt' и т.п.
    Возвращает SYMBOL в формате XXXUSDT или None.
    """
    t = re.sub(r"[^a-zA-Z]", "", text).upper()
    if not t:
        return None
    if t.endswith("USDT"):
        base = t[:-4]
    else:
        base = t
    if len(base) < 2 or len(base) > 10:
        return None
    symbol = base + "USDT"
    return _SYMBOL_ALIASES.get(symbol, symbol)
# ============ КОНЕЦ ФУНКЦИИ: normalize_symbol ============


# ============================================================================
# ФУНКЦИЯ: normalize_tf
# ОПИСАНИЕ: Нормализует таймфрейм к стандартному формату (1h, 4h, 15m, 1d)
#           Убирает пробелы, приводит к нижнему регистру
# ============================================================================
def normalize_tf(text: str) -> Optional[str]:
    """
    Принимает '1h', '4H', '15m', '1d', '1ч', '15м', '1д', '30' (без пробелов и в любом регистре).
    Возвращает стандартный формат: 1h, 15m, 1d
    Если указано только число - считает минутами (30 -> 30m)
    """
    t = re.sub(r"\s+", "", text).lower()
    
    # Замена русских букв на английские
    replacements = {
        'ч': 'h',
        'м': 'm', 
        'д': 'd',
        'н': 'w'
    }
    for ru, en in replacements.items():
        t = t.replace(ru, en)
    
    # Если только цифры - добавляем 'm' (минуты по умолчанию)
    if re.fullmatch(r"\d+", t):
        return t + "m"
    
    # Проверка формата
    if re.fullmatch(r"\d+[mhwd]", t):
        return t
    return None
# ============ КОНЕЦ ФУНКЦИИ: normalize_tf ============


